"""Generate docs/postman/revotask.postman_collection.json from scripts/api_steps.py.

Run order matters (variables like {{boardId}} are saved by earlier requests), so use the Collection Runner.
Set the `baseUrl` collection variable to <api origin>/api, for example https://<helipod-api-host>/api.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from api_steps import STEPS  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "docs" / "postman" / "revotask.postman_collection.json"
FOLDER_ORDER = ["health", "auth", "users", "boards", "columns", "cards", "comments", "notifications", "analytics"]


def placeholders(value):
    """Turn {var} placeholders into Postman {{var}} variables."""
    if isinstance(value, str):
        return value.replace("{", "{{").replace("}", "}}")
    if isinstance(value, dict):
        return {k: placeholders(v) for k, v in value.items()}
    if isinstance(value, list):
        return [placeholders(v) for v in value]
    return value


def test_script(step: dict) -> list[str]:
    lines = [f"pm.test('{step['name']}: status is {step['status']}', () => pm.response.to.have.status({step['status']}));",
             "const body = pm.response.json();",
             "pm.test('uses the data/error envelope', () => pm.expect(body).to.satisfy(b => 'data' in b || 'error' in b));"]
    for variable, path in step.get("save", {}).items():
        lines.append(f"pm.collectionVariables.set('{variable}', {'body.' + '.'.join(f'[{p}]' if p.isdigit() else p for p in path.split('.')).replace('.[', '[')});")
    return lines


def request_item(step: dict) -> dict:
    headers = [{"key": "Content-Type", "value": "application/json"}]
    request: dict = {
        "method": step["method"],
        "header": headers,
        "url": {"raw": "{{baseUrl}}" + placeholders(step["path"]), "host": ["{{baseUrl}}"], "path": [placeholders(step["path"]).lstrip("/")]},
    }
    if step.get("auth", True) and step["folder"] not in {"health"}:
        request["auth"] = {"type": "bearer", "bearer": [{"key": "token", "value": "{{token}}", "type": "string"}]}
    else:
        request["auth"] = {"type": "noauth"}
    if "body" in step:
        request["body"] = {"mode": "raw", "raw": json.dumps(placeholders(step["body"]), indent=2), "options": {"raw": {"language": "json"}}}
    return {"name": step["name"], "event": [{"listen": "test", "script": {"type": "text/javascript", "exec": test_script(step)}}], "request": request}


def main() -> int:
    folders = []
    for name in FOLDER_ORDER:
        items = [request_item(s) for s in STEPS if s["folder"] == name]
        if items:
            folders.append({"name": name, "item": items})
    collection = {
        "info": {
            "name": "RevoTask API",
            "description": "All 8 blueprints plus health. Set baseUrl to <api origin>/api, then run the collection in order. Generated by scripts/build_postman.py.",
            "schema": "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
        },
        "variable": [{"key": "baseUrl", "value": "http://127.0.0.1:5000/api"}, {"key": "email", "value": "postman-{{$timestamp}}@example.com"}],
        "event": [{"listen": "prerequest", "script": {"type": "text/javascript", "exec": [
            "if (!pm.collectionVariables.get('runEmail')) { pm.collectionVariables.set('runEmail', 'postman-' + Date.now() + '@example.com'); }",
            "pm.collectionVariables.set('email', pm.collectionVariables.get('runEmail'));"]}}],
        "item": folders,
    }
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(json.dumps(collection, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {TARGET.relative_to(ROOT)}: {sum(len(f['item']) for f in folders)} requests in {len(folders)} folders")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
