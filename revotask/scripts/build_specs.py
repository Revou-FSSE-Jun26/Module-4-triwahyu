"""Build the root /specs deliverable from the per-feature sources in .kiro/specs.

Authoring happens in .kiro/specs/NN-*/ (the Kiro-native layout). This script concatenates the slices into
specs/{requirements,design,tasks,CHANGELOG}.md plus specs/traceability.md. Generated files are committed and
drift-checked in CI:  python scripts/build_specs.py --check
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from specs_lib import ROOT, SPECS, feature_dirs, find_references, load_features, read  # noqa: E402

OUT = ROOT / "specs"
BANNER = "<!-- GENERATED by scripts/build_specs.py from .kiro/specs/*. Do not edit; edit the slice files and rerun. -->\n\n"
ROUND = re.compile(r"^## (R\d+)\b", re.MULTILINE)


def demote(text: str, levels: int = 1) -> str:
    """Push every heading down so each slice nests under its own section (skipping code fences)."""
    out, fenced = [], False
    for line in text.splitlines():
        if line.startswith("```"):
            fenced = not fenced
        out.append(("#" * levels + line) if not fenced and re.match(r"#{1,5}\s", line) else line)
    return "\n".join(out)


def slice_title(folder: Path) -> str:
    number, _, name = folder.name.partition("-")
    return f"{number} {name.replace('-', ' ').title()}"


def combine(filename: str, title: str, intro: str) -> str:
    parts = [BANNER, f"# {title}\n\n{intro}\n"]
    toc = ["## Contents\n"]
    body = []
    for folder in feature_dirs():
        anchor = slice_title(folder)
        toc.append(f"- {anchor}")
        text = read(folder / filename).strip()
        text = re.sub(r"\A# .*\n+", "", text)  # drop the slice's own H1
        body.append(f"## {anchor}\n\n{demote(text)}\n")
    return "\n".join(parts + ["\n".join(toc) + "\n"] + body)


def changelog() -> str:
    entries: list[tuple[int, str]] = []
    for folder in feature_dirs():
        text = read(folder / "CHANGELOG.md")
        matches = list(ROUND.finditer(text))
        for index, match in enumerate(matches):
            end = matches[index + 1].start() if index + 1 < len(matches) else len(text)
            block = text[match.start() : end].strip()
            block = re.sub(r"\n+See also .*\Z", "", block, flags=re.S)
            entries.append((int(match.group(1)[1:]), f"{block}\n\n_Slice: {slice_title(folder)}_"))
    entries.sort()
    head = (
        f"{BANNER}# Specification CHANGELOG\n\n"
        "Every refinement round: what the AI-generated artifact looked like **before**, the targeted prompt, "
        "what it looked like **after**, and the evidence. Entries come from each slice's `CHANGELOG.md` and are "
        f"ordered by round number. {len(entries)} rounds recorded.\n\n"
    )
    return head + "\n\n".join(block for _, block in entries) + "\n"


def traceability() -> str:
    features = load_features()
    ids = {r.id for f in features for r in f.requirements}
    refs = find_references(ids)
    lines = [BANNER, "# Traceability matrix\n",
             "Requirement → acceptance criteria → slice design → tasks → code or tests. Checked by `scripts/check_traceability.py`.\n",
             "| Requirement | Slice | ACs | Tasks | Referenced in |", "|---|---|---:|---|---|"]
    for feature in features:
        for req in feature.requirements:
            files = ", ".join(f"`{p}`" for p in refs[req.id][:3]) + (f" +{len(refs[req.id]) - 3}" if len(refs[req.id]) > 3 else "")
            lines.append(f"| {req.id} {req.title} | {slice_title(feature.folder)} | {len(req.acs)} | {', '.join(feature.tasks.get(req.id, []))} | {files} |")
    total_acs = sum(len(r.acs) for f in features for r in f.requirements)
    lines.append(f"\n**{len(ids)} requirements, {total_acs} acceptance criteria.**")
    return "\n".join(lines) + "\n"


def build() -> dict[str, str]:
    return {
        "requirements.md": combine("requirements.md", "RevoTask: Requirements",
                                   "Project brief, user roles, core features, tech stack, non-functional requirements, and every requirement with its acceptance criteria. Slice 00 holds the brief and cross-cutting requirements."),
        "design.md": combine("design.md", "RevoTask: Design",
                             "Architecture, data model (including the `Card` model with `db.Column(db.Float)`), and a table per slice mapping each requirement to a Flask route or Next.js page, its handler, service, schema and authorization."),
        "tasks.md": combine("tasks.md", "RevoTask: Tasks",
                            "Every route and page has a task naming the files that implement and test it. `[x]` means done and verified locally; `[ ]` needs the owner's accounts or live URLs."),
        "CHANGELOG.md": changelog(),
        "traceability.md": traceability(),
    }


def main() -> int:
    outputs = build()
    if "--check" in sys.argv:
        stale = [name for name, content in outputs.items() if not (OUT / name).exists() or (OUT / name).read_text(encoding="utf-8") != content]
        if stale:
            print("specs/ is out of date for: " + ", ".join(stale) + "\nRun: python scripts/build_specs.py")
            return 1
        print("specs/ is up to date.")
        return 0
    OUT.mkdir(exist_ok=True)
    for name, content in outputs.items():
        (OUT / name).write_text(content, encoding="utf-8", newline="\n")
        print(f"wrote specs/{name} ({len(content.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
